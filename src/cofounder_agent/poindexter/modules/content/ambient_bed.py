"""The music bed under a video's narration — one implementation for every lane.

A blog post's videos have carried a lo-fi instrumental bed since #679,
generated by ``generate_media_scripts`` and mixed by the compositor at a
constant -18 dB under the narration. News Shorts (``news_short`` graph) had no
step that made one, so they went out narration-only beside blog Shorts with
music. Both now call :func:`generate_ambient_bed`, so the prompt, the GPU lock,
the durable output path and the skip reporting are the same code.

Library, not a stage or an atom: the stage and the ``media.generate_ambient_bed``
atom both import it (an atom may import downward, never a stage).

:func:`generate_ambient_bed` renders and lets a busy GPU or a failed render
raise, so the stage keeps its own reporting. :func:`ambient_bed_or_nothing` is
the best-effort form for a graph node: every failure returns ``""`` and the
video renders without music, with a busy GPU reported as a
``media_gpu_busy_skip`` finding so a run of skips is visible.
"""

from __future__ import annotations

import logging
import re
from collections.abc import Awaitable, Callable
from typing import Any

from poindexter.modules.content.media_gpu_skip import surface_media_gpu_busy_skip
from poindexter.services.audio_gen_service import generate_audio, is_audio_gen_enabled
from poindexter.services.gpu_admission import GpuBusyError
from poindexter.services.gpu_scheduler import media_wait_budget_s

logger = logging.getLogger(__name__)

AMBIENT_PROMPT_FALLBACK = (
    "Lo-fi chillhop instrumental background music for a technology explainer "
    "video: mellow electric piano chords, warm bass, soft drum loop, 80 BPM, "
    "relaxed and focused. No vocals, no sound effects, no foley. "
    "Mood cues: {mood}"
)

# The model's maximum (~47 s). The compositor loops the bed under the whole
# video, so the longest clip means the fewest audible loop seams; the
# provider's 5 s default is sting-sized.
AMBIENT_BED_SECONDS = 47.0


def ambient_mood_cues(scenes: list[Any]) -> str:
    """First real scene description, reduced to plain mood text.

    Scene entries are SDXL *visual* prompts (and legacy rows carry markdown
    headers like ``### PART 1``). Fed verbatim to the music model they produce
    literal soundscapes — an office scene became engine-room hum — so the
    scene text is demoted to trailing mood cues inside a music-directed
    template, and markdown/header junk is stripped before use.
    """
    for entry in scenes or []:
        text = str(entry).strip()
        text = re.sub(r"^#+\s.*$", "", text, flags=re.MULTILINE)
        text = re.sub(r"[*#_`]+", " ", text)
        text = re.sub(r"^\s*Scene\s+\w+\s*[:.\-]\s*", "", text, flags=re.IGNORECASE)
        text = " ".join(text.split())
        if len(text) >= 20:
            return text[:160]
    return ""


def _audio_engine_label(site_config: Any) -> str | None:
    """The active audio engine's name, recorded as the GPU session's model."""
    if site_config is None:
        return None
    return str(site_config.get("audio_gen_engine", "") or "").strip() or None


async def generate_ambient_bed(
    mood: str,
    *,
    site_config: Any,
    output_dir: str,
    output_stem: str,
    task_id: Any,
    generate: Callable[..., Awaitable[Any]] | None = None,
    is_enabled: Callable[[Any], bool] | None = None,
) -> str:
    """Render the bed and return its path; ``""`` when audio gen is off.

    Raises :class:`GpuBusyError` when admission refuses the wait, and whatever
    the provider raises on a failed render. ``output_dir`` + ``output_stem``
    must be durable and deterministic (poindexter#1021): the path is frozen
    into task metadata and read by the render, in another container and
    possibly days later. ``generate`` / ``is_enabled`` default to the audio
    service; a caller passes its own module-level names so tests that patch
    those names keep working.
    """
    gen = generate or generate_audio
    enabled = is_enabled or is_audio_gen_enabled
    if site_config is None or not enabled(site_config):
        return ""

    template = site_config.get(
        "audio_gen_ambient_prompt_template", AMBIENT_PROMPT_FALLBACK,
    ) or AMBIENT_PROMPT_FALLBACK
    prompt = template.replace("{mood}", mood or "calm focus")
    from poindexter.services.gpu_scheduler import gpu

    # Its bounded wait is a term of the media stages' timeout budget: it sits
    # in front of the render that floor exists to protect.
    async with gpu.lock(
        "video", model=_audio_engine_label(site_config),
        task_id=str(task_id or "") or None, phase="video_ambient_bed",
        max_wait_s=media_wait_budget_s(), priority="background",
    ):
        result = await gen(
            prompt,
            "ambient",
            site_config=site_config,
            output_dir=output_dir,
            output_stem=output_stem,
            duration_s=AMBIENT_BED_SECONDS,
        )
    return str(getattr(result, "file_path", "") or "") if result is not None else ""


async def ambient_bed_or_nothing(
    mood: str,
    *,
    site_config: Any,
    output_dir: str,
    output_stem: str,
    task_id: Any,
    stage: str,
) -> str:
    """:func:`generate_ambient_bed`, but every failure returns ``""``.

    ``stage`` names the caller in the GPU-busy finding.
    """
    try:
        path = await generate_ambient_bed(
            mood, site_config=site_config, output_dir=output_dir,
            output_stem=output_stem, task_id=task_id,
        )
    except GpuBusyError as busy:
        logger.info("[MEDIA] video ambient bed skipped — GPU busy (%s)", busy.reason)
        surface_media_gpu_busy_skip(stage, busy, task_id=str(task_id or "") or None)
        return ""
    except Exception as exc:  # noqa: BLE001 — music is never worth failing a video for
        logger.warning("[MEDIA] audio_gen ambient bed failed: %s", exc)
        return ""
    if path:
        logger.info("[MEDIA] Video ambient bed: %s", path)
    return path


