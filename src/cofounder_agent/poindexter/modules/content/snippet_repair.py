"""Repair the search snippets of published posts that were cut mid-phrase.

Until 2026-10-28 the SEO step clamped its output at a word boundary
(``clamp_words`` at 160 characters, ``derive_seo_title`` at 60), so a model
that wrote a little long shipped a fragment. On that day 132 of 227 published
meta descriptions ended mid-sentence ("... are built for"), 19 SEO titles were
word-cut prefixes of the real title ("Choosing Between Local"), 26 dev-diary
descriptions were the placeholder "_What we shipped on <date>_", and one
title still carried a generation batch label. The SEO atom now fits instead
of cutting; this module repairs what it left behind.

Only broken fields change. A replacement is generated by the same atom
(``seo.generate_all_metadata``) and kept only when it passes the checks here;
otherwise the post is reported and left alone, because a weak snippet that is
complete still beats a confident wrong one.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from typing import Any

from poindexter.modules.content.atoms import _seo_common as sc

DESCRIPTION_MAX = 160
DESCRIPTION_MIN = 50
TITLE_MAX = 60
TITLE_MIN = 20

_SENTENCE_END = re.compile(r"""[.!?]["')\]]?$""")
_PLACEHOLDER = re.compile(r"^_?What we shipped on \d{4}-\d{2}-\d{2}_?$", re.IGNORECASE)
_BATCH_LABEL = re.compile(r"\s*\(\d{4}-\d{2}-\d{2} \d{2}:\d{2} batch [^)]*\)\s*$", re.IGNORECASE)
_MARKUP_START = re.compile(r"^\s*([*#>\-|]|\d+\.|_)")
# A title or heading that is a section label, not a title for this post.
_GENERIC_TITLES = {
    "what you'll learn", "introduction", "overview", "conclusion", "summary",
    "key takeaways", "table of contents", "tl;dr",
}
_NATURAL_BREAKS = (":", "—", "–", " -", "|", "?", "!", ".")


def description_is_cut(description: str | None) -> bool:
    """A description that stops mid-sentence: long, and no closing punctuation."""
    d = (description or "").strip()
    return len(d) >= 120 and not _SENTENCE_END.search(d)


def description_is_placeholder(description: str | None) -> bool:
    return bool(_PLACEHOLDER.match((description or "").strip()))


def seo_title_is_cut(seo_title: str | None, title: str | None) -> bool:
    """The SEO title is the real title cut mid-phrase.

    A prefix that stops at a natural break ("Head: tail" kept as "Head") is a
    fine title and is not reported.
    """
    seo, full = (seo_title or "").strip(), (title or "").strip()
    if not seo or len(full) <= len(seo) or not full.startswith(seo):
        return False
    rest = full[len(seo):]
    return not rest.lstrip().startswith(_NATURAL_BREAKS) and not seo.endswith(_NATURAL_BREAKS)


def strip_batch_label(title: str | None) -> str:
    return _BATCH_LABEL.sub("", title or "").strip()


def usable_description(text: str | None) -> bool:
    d = (text or "").strip()
    return (
        DESCRIPTION_MIN <= len(d) <= DESCRIPTION_MAX
        and bool(_SENTENCE_END.search(d))
        and not _MARKUP_START.match(d)
    )


def usable_title(text: str | None) -> bool:
    t = (text or "").strip()
    return (
        TITLE_MIN <= len(t) <= TITLE_MAX
        and t.lower().rstrip(":?!. ") not in _GENERIC_TITLES
        and not _MARKUP_START.match(t)
    )


@dataclass
class SnippetRepair:
    """What a repair would change on one post, and what it could not fix."""

    post_id: str
    slug: str
    changes: dict[str, tuple[str, str]] = field(default_factory=dict)  # column -> (old, new)
    unfixed: list[str] = field(default_factory=list)

    @property
    def problems(self) -> list[str]:
        return sorted(set(self.changes) | {u.split(":", 1)[0] for u in self.unfixed})


def diagnose(post: dict[str, Any]) -> list[str]:
    """Which of a post's snippet fields are broken."""
    found = []
    if strip_batch_label(post.get("title")) != (post.get("title") or "").strip():
        found.append("title")
    if seo_title_is_cut(post.get("seo_title"), post.get("title")):
        found.append("seo_title")
    if description_is_cut(post.get("seo_description")) or description_is_placeholder(post.get("seo_description")):
        found.append("seo_description")
    return found


async def plan_repair(post: dict[str, Any], *, site_config: Any, pool: Any) -> SnippetRepair:
    """The checked replacements for a post's broken snippet fields. Writes nothing."""
    from poindexter.modules.content.atoms import seo_generate_all_metadata as atom

    repair = SnippetRepair(post_id=str(post["id"]), slug=str(post.get("slug") or ""))
    broken = diagnose(post)
    title = (post.get("title") or "").strip()
    if "title" in broken:
        new_title = strip_batch_label(title)
        repair.changes["title"] = (title, new_title)
        title = new_title
    needs_llm = [f for f in broken if f in ("seo_title", "seo_description")]
    if not needs_llm:
        return repair

    class _DB:
        def __init__(self, p: Any) -> None:
            self.pool = p

    state = {
        "content": post.get("content") or "", "topic": title, "title": title,
        "canonical_title": title, "tags": [], "site_config": site_config,
        "database_service": _DB(pool),
    }
    generated = await atom.run(state)
    if "seo_title" in needs_llm:
        candidate = sc.clean_oneline(str(generated.get("seo_title") or ""))
        if usable_title(candidate):
            repair.changes["seo_title"] = (post.get("seo_title") or "", candidate)
        else:
            repair.unfixed.append(f"seo_title: generated {candidate!r} failed the checks")
    if "seo_description" in needs_llm:
        candidate = sc.clean_oneline(str(generated.get("seo_description") or ""))
        if usable_description(candidate):
            repair.changes["seo_description"] = (post.get("seo_description") or "", candidate)
        else:
            repair.unfixed.append(f"seo_description: generated {candidate!r} failed the checks")
    return repair


